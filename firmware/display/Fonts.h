#pragma once
/*
Purpose: The 7.0 typefaces (generated by tools/gen_fonts.py into Fonts.cpp).
  Label   crisp proportional pixel font, 7 px capitals, lower case.
  Medium, Large, Huge
          Barlow Semi Condensed Bold with soft edges, for big numbers and
          titles (Huge has digits and time marks only).
Glyphs are 4-bit coverage, blended into the frame by FrameCanvas::print.
All of it is in flash.
*/
#include <stdint.h>

namespace Fonts
{
struct Glyph
{
    uint16_t off;      // into the font's pixel data, two pixels a byte
    uint8_t  w, h;
    int8_t   dx, dy;   // from the pen position and the capitals' top
    uint8_t  adv;
};

struct Font
{
    const Glyph   *glyphs;
    const uint8_t *px;
    uint8_t        first, last;
    uint8_t        cap;    // capital height
    uint8_t        line;   // a comfortable line spacing
};

extern const Font Label, Medium, Large, Huge;

// Next character of a UTF-8 string as a glyph code: accented Latin letters
// fold to the plain letter (case kept), the degree sign to 127, the arrow
// "→" to '~' (which the Label font draws as an arrow); returns the
// bytes used (0 at the end).
inline int next(const char *s, uint8_t &out)
{
    const uint8_t b = (uint8_t)s[0];
    if (!b) return 0;
    if (b < 0x80) { out = b; return 1; }
    if (b == 0xC2 && (uint8_t)s[1] == 0xB0) { out = 127; return 2; }
    if (b == 0xE2 && (uint8_t)s[1] == 0x86 && (uint8_t)s[2] == 0x92) { out = '~'; return 3; }   // the arrow
    if (b == 0xC3 && s[1])
    {
        const uint8_t raw = (uint8_t)s[1], c = raw & 0xDF;
        const char up = c <= 0x85 ? 'A' : c == 0x87 ? 'C' : c <= 0x8B ? 'E' : c <= 0x8F ? 'I'
                      : c == 0x91 ? 'N' : (c <= 0x96 || c == 0x98) ? 'O' : (c >= 0x99 && c <= 0x9C) ? 'U'
                      : c == 0x9D ? 'Y' : '?';
        out = (raw >= 0xA0 && up != '?') ? (uint8_t)(up + 32) : (uint8_t)up;
        return 2;
    }
    int n = 1;
    while ((((uint8_t)s[n]) & 0xC0) == 0x80) ++n;
    out = '?';
    return n;
}

// Names that arrive in capitals ("HEATHROW", "LOS ANGELES") in title case,
// in place; a name already in mixed case is left alone.
inline void titleCase(char *s)
{
    bool lower = false;
    for (const char *p = s; *p; ++p) lower |= (*p >= 'a' && *p <= 'z');
    if (lower) return;
    bool start = true;
    for (char *p = s; *p; ++p)
    {
        if (*p >= 'A' && *p <= 'Z' && !start) *p = (char)(*p + 32);
        start = *p == ' ' || *p == '-' || *p == '/';
    }
}

// Labels made in capitals ("APPROACH 27L", "RARE SPOT") in sentence case,
// in place, leaving words with digits (27L, 20:15, A380) alone.
inline void sentenceCase(char *s)
{
    bool first = true;
    for (char *w = s; *w; )
    {
        char *e = w;
        bool digit = false;
        while (*e && *e != ' ') { digit |= (*e >= '0' && *e <= '9'); ++e; }
        if (!digit)
            for (char *p = w + (first ? 1 : 0); p < e; ++p)
                if (*p >= 'A' && *p <= 'Z') *p = (char)(*p + 32);
        first = false;
        w = *e ? e + 1 : e;
    }
}
}
