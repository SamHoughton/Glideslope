    // Timeline (ms)
    constexpr uint32_t kTouchdownMs = 1100;   // end of the approach and flare
    constexpr uint32_t kStoppedMs   = 2900;   // end of the rollout
    constexpr uint32_t kSmokeMs     = 750;    // tyre smoke lifetime
    constexpr uint32_t kGoAroundAtMs = 950;   // go-around: when it pitches up
    constexpr uint32_t kLiftOffMs   = 1700;   // take-off: end of the ground roll

    // Geometry (right-to-left; mirrored for the other direction)
    constexpr int kSurfaceY   = 58;           // runway surface rows 58-61
    constexpr int kKeysX      = 100;          // threshold piano keys x 100-108
    constexpr int kLightsX0   = 112;          // approach lights x 112-124
    constexpr int kTouchdownX = 84;           // sprite centre at touchdown
    constexpr int kStopX      = 24;           // sprite centre when stopped
    constexpr int kEntryY     = 14;           // sprite top on entry

    const Rgb kSurface   { 26,  28,  34};
    const Rgb kEdge      { 70,  74,  82};
    const Rgb kCentre    {150, 150, 155};
    const Rgb kKeys      {215, 215, 220};
    const Rgb kLightDim  {140,  92,  25};
    const Rgb kLightHead {255, 255, 255};
    const Rgb kText      {235, 240, 245};

    // London skyline on the horizon (generated by tools/skyline_workbench.py):
