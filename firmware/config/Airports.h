#pragma once
/*
Purpose: Offline lookups in the world airport table (config/AirportDb.h,
generated by tools/gen_airports.py from OurAirports): IATA code, position
and the city each airport serves, for the city-names setting and the globe.
Memory: all in flash; a lookup is a binary search with no allocation.
*/
#include <Arduino.h>
#include "models/AirportInfo.h"

namespace Airports
{
struct Place
{
    char        icao[5];
    char        iata[4];
    float       lat, lon;
    const char *city;   // in flash, never null once found
};

bool byIcao(const char *icao, Place &out);
bool byIata(const char *iata, Place &out);
// ICAO first, then IATA.
bool find(const AirportInfo &a, Place &out);
// The city an airport serves, or nullptr when it isn't in the table.
const char *city(const AirportInfo &a);
const char *city(const char *code);   // IATA (3 letters) or ICAO (4)
// The city in at most maxChars characters, for narrow columns: as it is,
// else without spaces (NEWYORK), else cut. False when not in the table.
bool shortCity(const char *code, size_t maxChars, char *out, size_t len);
// Fills outIata (3 characters + '\0'); false (and "") when not found.
bool icaoToIata(const char *icao, char outIata[4]);
}
