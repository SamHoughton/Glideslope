#!/usr/bin/env python3
"""
Generate firmware/display/LandMask.h: a 1-degree world land mask for the
globe screen, from Natural Earth's 1:110m land polygons (public domain).

Usage:
    python tools/gen_landmask.py                         # download the GeoJSON
    python tools/gen_landmask.py --local ne_110m_land.geojson

Bit (lon, lat) is set when the 1x1 degree cell whose south-west corner is
(-180 + lon, -90 + lat) is mostly land. Rows run south to north, 360 bits
(45 bytes) each: 8,100 bytes of flash.
"""

import argparse
import json
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson"
OUT = Path(__file__).parent.parent / "firmware" / "display" / "LandMask.h"
SS = 4   # supersampling per degree


def rings(geom):
    if geom["type"] == "Polygon":
        yield from geom["coordinates"][:1]   # outer ring; 1:110m land has no lakes worth keeping
    elif geom["type"] == "MultiPolygon":
        for poly in geom["coordinates"]:
            yield poly[0]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--local", metavar="FILE")
    args = ap.parse_args()
    data = json.loads(Path(args.local).read_text(encoding="utf-8") if args.local
                      else urllib.request.urlopen(URL).read().decode("utf-8"))

    im = Image.new("L", (360 * SS, 180 * SS), 0)
    d = ImageDraw.Draw(im)
    for f in data["features"]:
        for ring in rings(f["geometry"]):
            d.polygon([((lon + 180) * SS, (90 - lat) * SS) for lon, lat in ring], fill=255)
    small = im.resize((360, 180), Image.BOX)

    rows = []
    for lat in range(180):              # south to north
        y = 179 - lat
        bits = bytearray(45)
        for lon in range(360):
            if small.getpixel((lon, y)) >= 110:
                bits[lon >> 3] |= 0x80 >> (lon & 7)
        rows.append(bits)

    land = sum(bin(b).count("1") for r in rows for b in r)
    L = [
        "// Auto-generated by tools/gen_landmask.py - do not edit by hand.",
        "// Source: Natural Earth 1:110m land (https://www.naturalearthdata.com) - public domain.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "namespace LandMask",
        "{",
        "// 180 rows (90S to 90N) of 360 bits (180W to 180E), MSB first.",
        "static const uint8_t kBits[180 * 45] PROGMEM = {",
    ]
    for r in rows:
        L.append("    " + ",".join(f"0x{b:02x}" for b in r) + ",")
    L += [
        "};",
        "",
        "// True when the 1-degree cell holding (lat, lon) is land.",
        "inline bool isLand(float lat, float lon)",
        "{",
        "    int y = (int)floorf(lat + 90.0f), x = (int)floorf(lon + 180.0f);",
        "    if (y < 0) y = 0; else if (y > 179) y = 179;",
        "    x %= 360; if (x < 0) x += 360;",
        "    return (kBits[y * 45 + (x >> 3)] >> (7 - (x & 7))) & 1;",
        "}",
        "}  // namespace LandMask",
        "",
    ]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"{land} land cells of 64800 -> {OUT}")


if __name__ == "__main__":
    main()
