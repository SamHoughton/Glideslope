#!/usr/bin/env python3
"""
Plane icons for the London map: a top-view airliner silhouette rasterised at
16 headings (every 22.5 deg), supersampled for clean edges, in three sizes
(7.0): 5x5 for regional and light aircraft, 7x7 for narrowbodies, 9x9 for
widebodies, so a heavy looks heavy on the map.
Writes firmware/display/PlaneIcons.h; pass a folder to also save a preview.

Usage:  python tools/icon_workbench.py [preview_dir]
"""
import math, sys
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'firmware' / 'display' / 'PlaneIcons.h'
SS, THRESHOLD = 16, 128
SIZES = (5, 7, 9)

# Silhouette, nose up, in units where the 7x7 icon spans -3.5..3.5 (the
# other sizes scale it).
FUSE = [(0, -3.4), (0.5, -2.6), (0.5, 2.4), (0, 3.1), (-0.5, 2.4), (-0.5, -2.6)]
WING = [(0.45, -0.5), (3.4, 1.0), (3.4, 1.5), (0.45, 0.5), (-0.45, 0.5), (-3.4, 1.5), (-3.4, 1.0), (-0.45, -0.5)]
TAIL = [(0.35, 2.1), (1.5, 2.9), (1.5, 3.3), (0, 3.0), (-1.5, 3.3), (-1.5, 2.9), (-0.35, 2.1)]
# The heavy: a wider body and longer, more swept wings.
FUSE9 = [(0, -3.45), (0.62, -2.5), (0.62, 2.4), (0, 3.2), (-0.62, 2.4), (-0.62, -2.5)]
WING9 = [(0.5, -0.7), (3.45, 1.1), (3.45, 1.55), (0.5, 0.45), (-0.5, 0.45), (-3.45, 1.55), (-3.45, 1.1), (-0.5, -0.7)]


def raster(hdg, n):
    h = math.radians(hdg); c, s = math.cos(h), math.sin(h)
    k = n / 7.0
    half = n / 2.0
    big = Image.new('L', (n * SS, n * SS), 0)
    d = ImageDraw.Draw(big)
    polys = (FUSE9, WING9, TAIL) if n == 9 else (FUSE, WING, TAIL)
    for poly in polys:
        d.polygon([((k * (x * c - y * s) + half) * SS, (k * (x * s + y * c) + half) * SS) for x, y in poly], fill=255)
    px = big.resize((n, n), Image.BOX).load()
    th = {5: 70, 7: THRESHOLD, 9: 105}[n]
    lit = {(x, y) for y in range(n) for x in range(n) if px[x, y] >= th}
    if n == 9:   # no stray pixels: each one touches another along an edge
        lit = {(x, y) for (x, y) in lit if any((x + dx, y + dy) in lit for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))}
    fx, fy = math.sin(h), -math.cos(h)
    mid = (n - 1) / 2
    nose = max(lit, key=lambda p: (p[0] - mid) * fx + (p[1] - mid) * fy)
    return lit, nose


sets = {n: [raster(i * 22.5, n) for i in range(16)] for n in SIZES}

blocks = []
for n in SIZES:
    lines = []
    for i, (lit, nose) in enumerate(sets[n]):
        rows = [sum(1 << (n - 1 - x) for x in range(n) if (x, y) in lit) for y in range(n)] + [0] * (9 - n)
        lines.append(f'    {{ {{{", ".join(f"0x{r:03X}" for r in rows)}}}, {n}, {nose[0]}, {nose[1]} }},   // {i * 22.5:g} deg')
    blocks.append(f'    static const Icon k{n}x{n}[16] = {{\n' + '\n'.join(lines) + '\n    };')

OUT.write_text(f'''// Generated by tools/icon_workbench.py — do not edit by hand.
// Map plane icons: top-view silhouettes at 16 headings (every 22.5 deg), in
// three sizes: 5x5 (regional, light), 7x7 (narrowbody), 9x9 (widebody).
// Row bit (n - 1 - x) is pixel x; (noseX, noseY) is the nose pixel.
#pragma once
#include <stdint.h>

namespace PlaneIcons
{{
    struct Icon {{ uint16_t rows[9]; uint8_t n, noseX, noseY; }};

{chr(10).join(blocks)}

    enum Size : uint8_t {{ Small, Medium, Heavy }};

    // Icon for a true heading in degrees.
    inline const Icon &forHeading(float deg, Size size = Medium)
    {{
        int i = (int)((deg + 11.25f) / 22.5f) % 16;
        if (i < 0) i += 16;
        return size == Small ? k5x5[i] : size == Heavy ? k9x9[i] : k7x7[i];
    }}

    inline bool lit(const Icon &ic, int x, int y)
    {{
        return x >= 0 && y >= 0 && x < ic.n && y < ic.n && (ic.rows[y] & (1u << (ic.n - 1 - x)));
    }}
}}
''', encoding='utf-8')

if len(sys.argv) > 1:
    S = 10
    im = Image.new('RGB', (16 * 11 * S, 3 * 11 * S), (5, 6, 8))
    dr = ImageDraw.Draw(im)
    for row, n in enumerate(SIZES):
        for i, (lit, nose) in enumerate(sets[n]):
            for x, y in lit:
                X, Y = (i * 11 + 1 + x) * S, (row * 11 + 1 + y) * S
                dr.rectangle((X, Y, X + S - 2, Y + S - 2), fill=(255, 255, 255) if (x, y) == nose else (255, 90, 100))
    im.save(Path(sys.argv[1]) / 'plane_icons.png')
print('wrote', OUT.relative_to(ROOT))
