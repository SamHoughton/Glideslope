#!/usr/bin/env python3
"""Generate firmware/config/AirportTz.h: each airport's time zone, in the
same order as config/AirportDb.h, for local times at the other end of a
route (the "where it came from" page, 8.0).

  python tools/gen_timezones.py OPENFLIGHTS_AIRPORTS_DAT

Source: OpenFlights airports.dat (https://openflights.org/data, Open
Database License): the standard UTC offset and the daylight-saving region of
each airport. Its DST codes predate a few changes, corrected here by time-zone
name (Brazil and most of Mexico stopped changing their clocks). Airports it
doesn't list get an offset from their longitude and no daylight saving.

Each airport is one byte of offset (quarter hours + 64) and one of region:
'E' Europe, 'A' US/Canada, 'S' Chile/Paraguay, 'O' Australia, 'Z' New
Zealand, 'N' none.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / 'firmware' / 'config' / 'AirportDb.h'
OUT = ROOT / 'firmware' / 'config' / 'AirportTz.h'

NO_DST_ZONES = ('America/Sao_Paulo', 'America/Fortaleza', 'America/Recife', 'America/Bahia', 'America/Manaus',
                'America/Belem', 'America/Cuiaba', 'America/Campo_Grande', 'America/Porto_Velho',
                'America/Boa_Vista', 'America/Rio_Branco', 'America/Araguaina', 'America/Maceio',
                'America/Noronha', 'America/Santarem', 'America/Mexico_City', 'America/Monterrey',
                'America/Merida', 'America/Cancun', 'America/Chihuahua', 'America/Mazatlan',
                'America/Hermosillo', 'America/Bahia_Banderas', 'America/Regina', 'America/Phoenix',
                'Pacific/Honolulu', 'Asia/Tehran', 'Asia/Amman', 'Asia/Damascus', 'Europe/Istanbul',
                'Asia/Istanbul', 'Europe/Moscow', 'Europe/Minsk', 'Africa/Cairo', 'America/Asuncion_x')
DST_ZONES = {'America/Santiago': 'S', 'America/Asuncion': 'S', 'America/Punta_Arenas': 'N'}


def main():
    icaos = re.findall(r"\{\{'(.)','(.)','(.)','(.)'\},\{'.','.','.'\},(-?\d+),(-?\d+),", DB.read_text(encoding='utf-8'))
    order = [(''.join(m[:4]), int(m[5]) / 100.0) for m in icaos]
    tz = {}
    with open(sys.argv[1], newline='', encoding='utf-8') as f:
        for r in csv.reader(f):
            if len(r) < 12 or len(r[5]) != 4:
                continue
            try:
                off = float(r[9])
            except ValueError:
                continue
            dst, name = r[10], r[11]
            if name in DST_ZONES:
                dst = DST_ZONES[name]
            elif name in NO_DST_ZONES or dst not in 'EASOZ':
                dst = 'N'
            tz[r[5]] = (off, dst)
    known = 0
    offs, regs = [], []
    for icao, lon in order:
        if icao in tz:
            off, dst = tz[icao]
            known += 1
        else:
            off, dst = round(lon / 15.0), 'N'
        offs.append(int(round(off * 4)) + 64)
        regs.append(dst)
    lines = ['// Generated by tools/gen_timezones.py; do not edit by hand.',
             '// Source: OpenFlights airports.dat (https://openflights.org/data), Open Database License;',
             f'// {known} of {len(order)} airports listed there, the rest from their longitude.',
             '#pragma once', '#include <Arduino.h>', '', 'namespace AirportTz', '{',
             '// Standard UTC offset in quarter hours + 64, per AirportDb::kTable entry.',
             'static const uint8_t kOffset[] PROGMEM = {']
    for i in range(0, len(offs), 24):
        lines.append('    ' + ','.join(str(v) for v in offs[i:i + 24]) + ',')
    lines += ['};', "// Daylight-saving region: 'E' Europe, 'A' US/Canada, 'S' Chile/Paraguay, 'O' Australia,",
              "// 'Z' New Zealand, 'N' none.", 'static const char kRegion[] PROGMEM =']
    s = ''.join(regs)
    for i in range(0, len(s), 96):
        lines.append(f'    "{s[i:i + 96]}"')
    lines[-1] += ';'
    lines += ['}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {known}/{len(order)} from OpenFlights')


if __name__ == '__main__':
    main()
